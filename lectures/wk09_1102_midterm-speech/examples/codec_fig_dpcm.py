def draw(SVG, box, arrow):
    s = SVG(760, 430, "DPCM：只送「和預測值的差」；預測器一定要用解碼端也算得出的重建值")
    s.add('<defs><marker id="ah" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto">'
          '<path d="M0,0 L8,4 L0,8 z" fill="#333"/></marker></defs>')
    s.add('<text x="20" y="60" font-weight="bold">編碼端</text>')
    box(s, 20, 90, 60, 40, "x[n]", "white")
    box(s, 130, 80, 50, 60, "−", "#fff3e0")
    box(s, 230, 80, 90, 60, "量化\n（4 bits）")
    box(s, 370, 80, 70, 60, "送出\nq[n]", "#e8f5e9")
    box(s, 230, 200, 90, 60, "反量化\n×Δ")
    box(s, 130, 200, 50, 60, "+", "#fff3e0")
    box(s, 20, 200, 80, 60, "預測器\nx̂=x̃[n−1]")
    arrow(s, 80, 110, 130, 110)
    arrow(s, 180, 110, 230, 110, "e[n]")
    arrow(s, 320, 110, 370, 110, "q[n]")
    arrow(s, 275, 140, 275, 200)
    s.add('<text x="283" y="175" fill="#1f77b4">q[n]</text>')
    arrow(s, 230, 230, 180, 230, "ê[n]")
    arrow(s, 130, 230, 100, 230)
    s.add('<text x="115" y="222" text-anchor="middle" fill="#1f77b4">x̃[n]</text>')
    s.add('<path d="M60,200 L60,165 L155,165" fill="none" stroke="#333" stroke-width="1.5"/>')
    arrow(s, 155, 165, 155, 140)
    arrow(s, 155, 165, 155, 200)
    s.add('<text x="105" y="160" text-anchor="middle" fill="#1f77b4">x̂[n]</text>')
    s.add('<text x="20" y="300" font-weight="bold">解碼端（和編碼端右下角一模一樣）</text>')
    box(s, 20, 330, 70, 50, "收到\nq[n]", "#e8f5e9")
    box(s, 140, 330, 90, 50, "反量化\n×Δ")
    box(s, 280, 330, 50, 50, "+", "#fff3e0")
    box(s, 380, 330, 90, 50, "預測器\nx̂=x̃[n−1]")
    box(s, 520, 330, 70, 50, "x̃[n]\n→ 喇叭", "white")
    arrow(s, 90, 355, 140, 355)
    arrow(s, 230, 355, 280, 355, "ê[n]")
    arrow(s, 330, 355, 380, 355, "x̃[n]")
    arrow(s, 470, 355, 520, 355)
    s.add('<path d="M425,330 L425,310 L305,310 L305,330" fill="none" stroke="#333" stroke-width="1.5" marker-end="url(#ah)"/>')
    s.add('<text x="365" y="305" text-anchor="middle" fill="#1f77b4">x̂[n]</text>')
    s.add('<text x="470" y="110" fill="#d62728">重點：編碼端預測用的是 x̃（重建值），</text>')
    s.add('<text x="470" y="128" fill="#d62728">不是原始的 x——這樣兩邊的預測一模一樣，</text>')
    s.add('<text x="470" y="146" fill="#d62728">量化誤差才不會一路累積。</text>')
    s.add('<text x="470" y="190" fill="#555">ADPCM 多做一件事：Δ 隨 |q[n]| 自動調整</text>')
    s.add('<text x="470" y="208" fill="#555">（上一個 q 大 → Δ 放大；小 → 縮小），</text>')
    s.add('<text x="470" y="226" fill="#555">兩邊用同一張表，所以不用把 Δ 送過去。</text>')
    s.save("dpcm_block.svg")
